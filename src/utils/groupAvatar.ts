/**
 * 群头像的**布局纯逻辑**（会话列表那一格）。
 *
 * ## 为什么换掉「微信式 2×2 九宫格」
 *
 * 旧实现是 2×2 四格塞成员脸：1 人时只有左上角一张脸（看着像渲染坏了）、
 * 2 人时上半张脸（下面空一半）、3 人时缺一个角。用户 2026-11-15 的原话是
 * 「一个人在角上、两个人是上半个、三个人还有一个缺角是空的」——
 * 问题不是「格子小」，而是**没被填满的那部分看起来像坏了**。
 *
 * ## 新形状：交叠的「簇」
 *
 * 成员少的时候**把脸放大到互相交叠**，让整块圆被铺满：
 *
 * | 成员数 | 形状 | 角标 |
 * |---|---|---|
 * | 1 | 整块圆就是那一张脸 | 群标（`users` 图标） |
 * | 2 | 两张脸沿对角线交叠 | 群标 |
 * | 3 | 三张脸摆成三角形 | 群标 |
 * | 4+ | 三角形簇（不画第 4 张） | 群标 |
 *
 * 交叠而不是平铺，两个理由：
 * ① **平铺必然留空角**（2×2 只有四格，人少于 4 就空），交叠能做到「视觉上填满」；
 * ② 交叠的多张脸**一眼就是「好几个人」**，而 2×2 里的两张脸只是「上半张图」。
 *
 * 角标存在的唯一理由：**一个人也能建群**。单看一张脸，它和单聊头像没有区别 ——
 * 角标是「这是个群」这句话的载体（`users` 图标），不是装饰。
 *
 * 这里的数字是**比例**（相对容器边长 0~1），不是像素：容器大小是 CSS 变量
 * （`--gosslan-row-avatar`），在不同断点下不一样，写死像素会在别处崩。
 */

/** 一个成员在簇里的位置（比例）。 */
export interface GroupAvatarSlot {
  /** 直径（相对容器边长）。 */
  size: number;
  /** 左上角横坐标（相对容器边长）。 */
  left: number;
  /** 左上角纵坐标（相对容器边长）。 */
  top: number;
  /** 叠放次序（大的在上面）。 */
  z: number;
}

/** 簇里的一张脸（成员资料由调用点准备好）。 */
export interface GroupAvatarMember {
  /** 种子键（一般是成员设备 id）：决定默认脸的底色与表情。 */
  id: string;
  /** 头像图地址；没有就落回默认脸。 */
  avatar?: string | null;
}

/** 角标：群标（`users` 图标）。永远只有这一种 —— 它要说的只有一句话「这是群」。 */
export interface GroupAvatarChip {
  kind: "group";
}

export interface GroupAvatarLayout {
  /** 要画的脸（最多 3 张）。 */
  slots: GroupAvatarSlot[];
  /** 角标；`null` = 不画（成员数为 0 时）。 */
  chip: GroupAvatarChip | null;
}

/** 最多画几张脸。超过的部分不画（成员总数由群名/成员面板给出，不挤在头像里）。 */
export const GROUP_AVATAR_MAX_FACES = 3;

/**
 * 按成员数算布局。**纯函数**：没有 DOM、没有 store ⇒ 可直接单测。
 *
 * 形状约定（改这里必须同时改 `groupAvatar.test.ts` 的判据）：
 * - 1 人：一张脸铺满（`size = 1`），角标是群标；
 * - 2 人：两张 `0.80` 的脸沿对角线交叠（左上 / 右下）；
 * - 3 人：三张 `0.68` 的脸摆成三角形（上中 / 左下 / 右下）；
 * - 4+：三角形簇（多出来的人不画在头像里）。
 *
 * 尺寸是**覆盖率与可辨识度的折中**：脸再大一点，交叠就深到只剩一条边（看不出是谁）；
 * 再小一点，圆里就空出明显的两块。判据（`groupAvatar.test.ts`）钉住两件事：
 * 四个象限中心都被脸盖住（旧的 2×2 形状在这种判据下会红）+ 圆内覆盖率 ≥ 85%。
 *
 * 为什么不画超过 3 张：再往上挤，每张脸就只剩一条边 —— 看不出是谁，
 * 而「看不出是谁的脸」对头像来说是零价值。总数去看群名与成员面板。
 */
export function groupAvatarLayout(memberCount: number): GroupAvatarLayout {
  const n = Math.max(0, Math.floor(memberCount));
  if (n === 0) return { slots: [], chip: null };

  if (n === 1) {
    return {
      slots: [{ size: 1, left: 0, top: 0, z: 1 }],
      chip: { kind: "group" },
    };
  }

  if (n === 2) {
    return {
      slots: [
        { size: 0.8, left: 0, top: 0, z: 1 },
        { size: 0.8, left: 0.2, top: 0.2, z: 2 },
      ],
      chip: { kind: "group" },
    };
  }

  // 3 人及以上：三角形簇（上中 / 左下 / 右下），彼此交叠 ⇒ 没有空角。
  return {
    slots: [
      { size: 0.68, left: 0.16, top: 0, z: 3 },
      { size: 0.68, left: 0, top: 0.32, z: 1 },
      { size: 0.68, left: 0.32, top: 0.32, z: 2 },
    ],
    chip: { kind: "group" },
  };
}
