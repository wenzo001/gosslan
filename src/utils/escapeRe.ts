/**
 * 正则字面量转义（把用户提供的字符串安全地嵌进 RegExp）。
 *
 * 为什么单独一份：这个函数曾在 `emoji.ts` 与 `linkify.ts` 里各有一份**逐字相同**的私有副本，
 * 而 `linkify.ts` 那份又导出给 `messages.ts` 用 —— 三处共用、两处定义。
 * 正则表达式写错不会报错，只会**静默匹配不到**（比如忘了转 `]` 或 `\`），
 * 所以"改一处漏一处"的代价是某个功能突然失灵且看不出原因。
 */

/** 把 `s` 里的正则元字符全部转义，返回可安全嵌入 `new RegExp(...)` 的字符串。 */
export function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
