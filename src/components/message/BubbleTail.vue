<script setup lang="ts">
/**
 * 聊天气泡的「小尾巴」—— 指向头像的那枚叶形。
 *
 * ## 为什么是一个组件而不是每处内联一段 SVG
 *
 * 用户 2026-10-23 两轮反馈：① 尾巴吊在气泡底部、跟头像不搭；② 尾巴**上边不够丝滑**，
 * 而且「气泡有边框、尾巴没有」⇒ 接缝处两条线对不上，hover 时还能看出它是贴上去的一块。
 * 用 border 拼三角形/圆角在 12px 这个尺寸上怎么调都有折点；而"和气囊共用一条轮廓线"
 * 需要**同一支描边** —— 只有路径能同时给出曲率连续的外缘和沿边界的 1px 线。
 *
 * 所以这里收成**一个家**（形状只有这一份；五个气泡组件都用它，见 `designGuards` 的
 * "内联 svg 的家" 与 "气泡尖角位置只有一个家" 两条判据）。
 *
 * ## 几何契约（改一个必须同时改另一个）
 *
 * - 盒子 14×14；`style.css` 的 `.bubble-tail` 负责定位与颜色，这里只管形状。
 * - 朝左（对方消息）那一支：气泡**外框**在盒子 x=10；朝右（自己）在 x=4。
 *   对应 `.tail-other{left:-10px}` / `.tail-mine{right:-10px}` —— 那两个常数就是从这里来的。
 * - 2026-10-24 用户口径：尾巴挂在气泡**左下角、贴底边**，尖朝外，**不再向下伸**。
 *   盒子底边与气泡底边齐（`bottom: 0`）⇒ 尾巴整体落在气泡高度内，下沿不出界。
 * - 填充层（`tail-fill`）从气泡边缘内侧起笔：把气泡左/右边缘 `y=4..14` 整段边框盖掉，
 *   并且**一直盖到底边** —— 尾巴侧的下圆角已由 `style.css` 拉平，这里不再留任何缺口。
 * - 描边层（`tail-line`）是一条**开口**路径：从气泡边缘 `(10,4)` 出发，绕外缘到尖端，
 *   再从尖端弯回气泡底边 `(10,14)` —— 上端接气泡竖边框、下端接气泡底边框，
 *   三条线首尾相接，看上去是同一支轮廓（用户 2026-10-25：尾巴和气泡要"连贯、丝滑"）。
 *   ⚠️ 两端的**切线方向**必须顺着边框：起点控制点必须在 `(10,6)`（竖直向下），
 *   终点控制点必须在 `(7,14)`（水平向右）。否则即使端点重合，接缝处也会鼓起一个
 *   "小揪揪"——用户 2026-10-25 第二轮报的就是这个折点。
 * - 描边色取 `--bubble-line`（由 `useMessageDisplay` 按这条消息的边框色给出），
 *   自己的消息边框透明 ⇒ 描边也透明，只留填充。
 */
// 2026-10-24：群聊不渲染（`tail` 由 MessageItem 按 `isGroup` 给）；单聊挂在左下/右下角贴底边。
// 朝向靠 `.tail-mine { scaleX(-1) }` 镜像，形状只有一份 —— 两份路径迟早会漂。
withDefaults(defineProps<{ mine?: boolean }>(), { mine: false });
</script>

<template>
